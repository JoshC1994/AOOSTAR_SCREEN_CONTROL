export function createWidgetFromType(type: WidgetType, x = 24, y = 24): ScreenWidget {
  const spec = WIDGET_CATALOG.find((item) => item.type === type);
  const id = `w-${Date.now()}-${Math.random().toString(36).slice(2, 6)}`;
  return {
    id,
    type,
    x,
    y,
    w: spec?.defaultW ?? 220,
    h: spec?.defaultH ?? 110,
    title: spec?.label ?? 'Block',
    accentColor: '#F59E0B',
    textColor: '#F1F5F9',
    bgColor: '#0F1520',
    bgOpacity: 0.78,
    borderOpacity: 0.25,
    fontScale: 1,
    fontFamily: 'mono',
    fontSizePreset: 'md',
    entityId:
      type === 'entity_number'
        ? 'server.cpu_temp'
        : type === 'apex_area'
          ? 'server.cpu_percent'
          : type === 'apex_radial'
            ? 'server.array_used_pct'
            : undefined,
    entityIds:
      type === 'entity_list'
        ? ['server.cpu_percent', 'server.ram_percent', 'server.cpu_temp', 'server.array_used_pct']
        : type === 'apex_area'
          ? ['server.cpu_percent', 'server.ram_percent']
          : type === 'apex_bar' || type === 'apex_hbar'
            ? ['disk.parity1.temp_c', 'disk.disk1.temp_c', 'disk.disk2.temp_c', 'disk.nvme0.temp_c']
            : undefined,
    chartVariant: 'area',
    binding:
      type === 'apex_area'
        ? 'cpu_percent'
        : type === 'apex_radial'
          ? 'array_percent'
          : type === 'apex_bar'
            ? 'disk_temps'
            : undefined,
    haEntityId: type === 'ha_entity' ? '' : undefined,
    customText: type === 'custom_text' ? '{{server.hostname}} · {{server.cpu_percent}}%' : undefined,
    htmlCode: type === 'custom_html' ? DEFAULT_HTML_CODE : undefined,
    imageUrl: type === 'image_layer' ? PRESET_BACKGROUNDS[2].url : undefined,
    imageFit: 'cover',
    apexCode: type === 'apex_custom' ? DEFAULT_APEX_CODE : undefined,
    maxItems: 4,
    chartSmooth: true,
  };
}

